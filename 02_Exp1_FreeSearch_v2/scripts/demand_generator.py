#!/usr/bin/env python3
"""
Milestone 1C-1 - Poisson arrival schedule generator.

This module generates a continuous-time Poisson arrival process and can
derive the arrival rate from offered parking load:

    rho = lambda * E[T_park] / C_eff

Therefore:

    lambda = rho * C_eff / E[T_park]

Important:
- The generated arrival times are continuous-valued seconds.
- Do not quantize arrivals here. SUMO/control-step insertion policy belongs
  to the integration layer (Milestone 1C-3).
- Direct-rate mode is intended for smoke/debug tests.
- Formal experiments must use frozen rho, C_eff, E[T_park], seed, and horizon.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import random
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Iterable


GENERATOR_VERSION = "1C1-v1"


class DemandError(ValueError):
    """Raised when demand-generation parameters are invalid."""


@dataclass(frozen=True)
class ArrivalEvent:
    vehicle_id: str
    arrival_time_s: float


def arrival_rate_from_load(
    rho: float,
    c_eff: int,
    mean_parking_s: float,
) -> float:
    """Return lambda in vehicles/second."""
    rho = float(rho)
    c_eff = int(c_eff)
    mean_parking_s = float(mean_parking_s)

    if rho < 0:
        raise DemandError("rho must be >= 0.")
    if c_eff <= 0:
        raise DemandError("c_eff must be > 0.")
    if mean_parking_s <= 0:
        raise DemandError("mean_parking_s must be > 0.")

    return rho * c_eff / mean_parking_s


def _positive_uniform(rng: random.Random) -> float:
    """Return U strictly inside (0, 1]."""
    while True:
        u = rng.random()
        if u > 0.0:
            return u


def generate_poisson_arrivals(
    rate_per_s: float,
    start_time_s: float,
    end_time_s: float,
    seed: int,
    id_prefix: str = "veh",
) -> list[ArrivalEvent]:
    """
    Generate a homogeneous Poisson arrival process on [start_time_s, end_time_s).

    Inter-arrival times are generated by inverse-transform sampling:
        Delta t = -ln(U) / lambda
    """
    rate_per_s = float(rate_per_s)
    start_time_s = float(start_time_s)
    end_time_s = float(end_time_s)

    if rate_per_s < 0:
        raise DemandError("rate_per_s must be >= 0.")
    if start_time_s < 0:
        raise DemandError("start_time_s must be >= 0.")
    if end_time_s <= start_time_s:
        raise DemandError("end_time_s must be greater than start_time_s.")
    if not isinstance(seed, int):
        raise DemandError("seed must be an integer.")
    if not id_prefix:
        raise DemandError("id_prefix must be non-empty.")

    if rate_per_s == 0:
        return []

    rng = random.Random(seed)
    events: list[ArrivalEvent] = []
    t = start_time_s
    idx = 0

    while True:
        u = _positive_uniform(rng)
        dt = -math.log(u) / rate_per_s
        t += dt

        if t >= end_time_s:
            break

        events.append(
            ArrivalEvent(
                vehicle_id=f"{id_prefix}_{idx:06d}",
                arrival_time_s=t,
            )
        )
        idx += 1

    return events


def schedule_fingerprint(events: Iterable[ArrivalEvent]) -> str:
    """
    SHA-256 fingerprint of the logical schedule.

    Fixed decimal formatting makes the fingerprint independent of CSV writer
    formatting while preserving sufficient precision for reproduction.
    """
    h = hashlib.sha256()
    for event in events:
        line = f"{event.vehicle_id},{event.arrival_time_s:.12f}\n"
        h.update(line.encode("utf-8"))
    return h.hexdigest()


def write_schedule_csv(path: Path, events: list[ArrivalEvent]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["vehicle_id", "arrival_time_s"],
        )
        writer.writeheader()
        for e in events:
            writer.writerow(
                {
                    "vehicle_id": e.vehicle_id,
                    "arrival_time_s": f"{e.arrival_time_s:.12f}",
                }
            )


def load_effective_capacity(network_summary: Path) -> int:
    if not network_summary.exists():
        raise DemandError(
            f"network summary does not exist: {network_summary}"
        )
    data = json.loads(network_summary.read_text(encoding="utf-8"))
    if data.get("status") != "PASS":
        raise DemandError(
            f"network summary status must be PASS, got {data.get('status')!r}"
        )
    try:
        c_eff = int(data["effective_capacity"])
    except (KeyError, TypeError, ValueError) as exc:
        raise DemandError(
            "network summary has no valid effective_capacity."
        ) from exc
    if c_eff <= 0:
        raise DemandError("effective_capacity must be > 0.")
    return c_eff


def parse_args() -> argparse.Namespace:
    project_root = Path(__file__).resolve().parent.parent
    default_summary = project_root / "validation" / "network_summary.json"
    default_output = project_root / "validation" / "demand_generator"

    p = argparse.ArgumentParser(
        description="Generate a reproducible Poisson arrival schedule."
    )

    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--rate-per-s",
        type=float,
        help="Direct Poisson arrival rate [vehicles/s]; smoke/debug mode.",
    )
    mode.add_argument(
        "--rho",
        type=float,
        help="Offered parking load. Requires --mean-parking-s.",
    )

    p.add_argument(
        "--mean-parking-s",
        type=float,
        help="Expected parking duration [s], required with --rho.",
    )
    p.add_argument(
        "--network-summary",
        type=Path,
        default=default_summary,
        help="Validated network summary used to read C_eff.",
    )
    p.add_argument("--start-s", type=float, default=0.0)
    p.add_argument("--duration-s", type=float, required=True)
    p.add_argument("--seed", type=int, required=True)
    p.add_argument("--id-prefix", default="veh")
    p.add_argument("--output-dir", type=Path, default=default_output)
    return p.parse_args()


def main() -> int:
    args = parse_args()

    start_s = float(args.start_s)
    end_s = start_s + float(args.duration_s)

    if args.duration_s <= 0:
        raise DemandError("duration-s must be > 0.")

    if args.rate_per_s is not None:
        rate_per_s = float(args.rate_per_s)
        mode = "direct_rate_debug"
        c_eff = None
        rho = None
        mean_parking_s = None
        formal_parameterization = False
    else:
        if args.mean_parking_s is None:
            raise DemandError("--mean-parking-s is required with --rho.")
        c_eff = load_effective_capacity(args.network_summary.resolve())
        rho = float(args.rho)
        mean_parking_s = float(args.mean_parking_s)
        rate_per_s = arrival_rate_from_load(
            rho=rho,
            c_eff=c_eff,
            mean_parking_s=mean_parking_s,
        )
        mode = "offered_load"
        formal_parameterization = True

    events = generate_poisson_arrivals(
        rate_per_s=rate_per_s,
        start_time_s=start_s,
        end_time_s=end_s,
        seed=args.seed,
        id_prefix=args.id_prefix,
    )

    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / f"arrivals_seed{args.seed}.csv"
    json_path = output_dir / f"arrival_manifest_seed{args.seed}.json"

    write_schedule_csv(csv_path, events)

    expected_count = rate_per_s * (end_s - start_s)
    manifest = {
        "generator_version": GENERATOR_VERSION,
        "arrival_model": "homogeneous_poisson",
        "parameterization_mode": mode,
        "formal_parameterization": formal_parameterization,
        "seed": args.seed,
        "start_time_s": start_s,
        "end_time_s": end_s,
        "duration_s": end_s - start_s,
        "rate_per_s": rate_per_s,
        "rate_per_hour": rate_per_s * 3600.0,
        "rho": rho,
        "effective_capacity": c_eff,
        "mean_parking_s": mean_parking_s,
        "expected_arrival_count": expected_count,
        "generated_arrival_count": len(events),
        "schedule_sha256": schedule_fingerprint(events),
        "schedule_csv": str(csv_path),
    }
    json_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print("=" * 76)
    print("T-ITS EXPERIMENT 1 - MILESTONE 1C-1 POISSON ARRIVAL GENERATOR")
    print("=" * 76)
    print(f"Mode               : {mode}")
    print(f"Seed               : {args.seed}")
    print(f"Window             : [{start_s:.3f}, {end_s:.3f}) s")
    print(f"lambda             : {rate_per_s:.12f} veh/s")
    print(f"lambda             : {rate_per_s * 3600.0:.6f} veh/h")

    if mode == "offered_load":
        print(f"rho                : {rho}")
        print(f"C_eff              : {c_eff}")
        print(f"E[T_park]          : {mean_parking_s:.3f} s")

    print(f"Expected count     : {expected_count:.3f}")
    print(f"Generated count    : {len(events)}")
    print(f"Schedule SHA-256   : {manifest['schedule_sha256']}")
    print(f"CSV                : {csv_path}")
    print(f"Manifest           : {json_path}")

    if mode == "direct_rate_debug":
        print()
        print("NOTICE: direct-rate mode is for smoke/debug use, not formal results.")

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except DemandError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(2)
